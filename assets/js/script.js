function initCursorParticles() {
  var canvas = document.createElement('canvas');
  canvas.id = 'particleFx';
  canvas.setAttribute('aria-hidden', 'true');
  document.body.appendChild(canvas);
  var ctx = canvas.getContext('2d');
  if (!ctx) return;

  var particles = [];
  var lastSpawn = 0;
  var raf = null;
  var running = false;
  var colors = ['#0f0', '#f0f', '#0ff', '#ff0', '#f00', '#ff69b4'];
  function modeChars() {
    var m = getTrailMode();
    if (m === 'hearts') return ['\u2665', '\u2661', '\u2764'];
    if (m === 'baka') return ['BAKA', 'baka', 'Baka!'];
    if (m === 'binary') return ['0', '1'];
    return ['\u2728', '\u26A1', '\u2B50', '\u2665', '0', '1', '>', '\u2605'];
  }

  function resize() {
    canvas.width = window.innerWidth;
    canvas.height = window.innerHeight;
  }
  resize();
  window.addEventListener('resize', resize);

  function ensureLoop() {
    if (running) return;
    running = true;
    raf = requestAnimationFrame(tick);
  }

  function tick(t) {
    if (!particles.length || isMotionReduced()) {
      ctx.clearRect(0, 0, canvas.width, canvas.height);
      particles.length = 0;
      running = false;
      raf = null;
      return;
    }
    raf = requestAnimationFrame(tick);
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    for (var i = particles.length - 1; i >= 0; i--) {
      var p = particles[i];
      var age = t - p.born;
      if (age > p.life) {
        particles.splice(i, 1);
        continue;
      }
      var prog = age / p.life;
      p.y -= p.vy;
      ctx.globalAlpha = 1 - prog;
      ctx.fillStyle = p.color;
      ctx.font = 'bold ' + p.size + 'px Courier New, monospace';
      ctx.fillText(p.ch, p.x, p.y);
    }
    ctx.globalAlpha = 1;
  }

  document.addEventListener('mousemove', function(e) {
    if (isMotionReduced()) return;
    if (getTrailMode() === 'off') return;
    if (Math.random() > 0.55) return;
    var now = performance.now();
    if (now - lastSpawn < SITE.particleThrottleMs) return;
    lastSpawn = now;
    if (particles.length >= SITE.particleMax) particles.shift();
    var chars = modeChars();
    var ch = chars[Math.floor(Math.random() * chars.length)];
    particles.push({
      x: e.clientX,
      y: e.clientY,
      ch: ch,
      color: colors[Math.floor(Math.random() * colors.length)],
      size: (getTrailMode() === 'baka' ? 9 : 10) + Math.random() * 10,
      vy: 0.4 + Math.random() * 0.5,
      born: now,
      life: 800
    });
    ensureLoop();
  });
}

