function initMatrix() {
  var c = document.getElementById('matrix');
  if (!c) return;
  var ctx = c.getContext('2d');
  if (!ctx) return;
  var parent = c.parentElement;
  var chars = 'アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヲン0123456789';
  var fontSize = 10;
  var drops = [];
  var inView = true;
  var rafId = null;
  var lastDraw = 0;

  function resize() {
    c.width = parent.offsetWidth;
    c.height = parent.offsetHeight;
    var cols = Math.max(1, Math.floor(c.width / fontSize));
    while (drops.length < cols) {
      drops.push(Math.floor(Math.random() * -c.height / fontSize));
    }
    if (drops.length > cols) drops.length = cols;
  }
  resize();
  window.addEventListener('resize', resize);

  if ('IntersectionObserver' in window) {
    var io = new IntersectionObserver(
      function(entries) {
        inView = entries[0] && entries[0].isIntersecting;
      },
      { threshold: 0.05 }
    );
    io.observe(parent);
  }

  function draw() {
    ctx.fillStyle = 'rgba(0, 0, 0, 0.05)';
    ctx.fillRect(0, 0, c.width, c.height);
    ctx.font = fontSize + 'px monospace';
    for (var i = 0; i < drops.length; i++) {
      var ch = chars[Math.floor(Math.random() * chars.length)];
      ctx.fillStyle = Math.random() > 0.95 ? '#fff' : '#0f0';
      ctx.fillText(ch, i * fontSize, drops[i] * fontSize);
      if (drops[i] * fontSize > c.height && Math.random() > 0.975) drops[i] = 0;
      drops[i]++;
    }
  }

  function loop(t) {
    rafId = requestAnimationFrame(loop);
    if (document.hidden || !inView || isMotionReduced()) return;
    if (t - lastDraw < SITE.matrixFrameMs) return;
    lastDraw = t;
    draw();
  }
  rafId = requestAnimationFrame(loop);
}

