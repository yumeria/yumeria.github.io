function shuffleUniqueModels(count) {
  var n = SITE.modelCount;
  var pool = [];
  for (var i = 0; i < n; i++) pool.push(i);
  for (var j = pool.length - 1; j > 0; j--) {
    var k = Math.floor(Math.random() * (j + 1));
    var tmp = pool[j];
    pool[j] = pool[k];
    pool[k] = tmp;
  }
  if (count <= n) return pool.slice(0, count);
  // more imgs than models: cycle shuffled packs
  var out = [];
  while (out.length < count) {
    out = out.concat(pool);
  }
  return out.slice(0, count);
}

