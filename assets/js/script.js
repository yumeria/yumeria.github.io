// ===== STORAGE HELPERS =====
function storageGet(key, fallback) {
  try {
    var v = localStorage.getItem(key);
    return v == null ? fallback : v;
  } catch (e) {
    return fallback;
  }
}

function storageSet(key, value) {
  try {
    localStorage.setItem(key, value);
    return true;
  } catch (e) {
    return false;
  }
}

function storageGetJSON(key, fallback) {
  try {
    var raw = localStorage.getItem(key);
    if (raw == null) return fallback;
    var parsed = JSON.parse(raw);
    return parsed == null ? fallback : parsed;
  } catch (e) {
    return fallback;
  }
}

function storageSetJSON(key, value) {
  try {
    localStorage.setItem(key, JSON.stringify(value));
    return true;
  } catch (e) {
    return false;
  }
}

// ===== REDUCED MOTION =====
var motionReduced = false;

function isMotionReduced() {
  return motionReduced;
}

function applyMotionPreference(mode) {
  // mode: 'reduce' | 'full'
  var html = document.documentElement;
  motionReduced = mode === 'reduce';
  html.classList.toggle('reduce-motion', motionReduced);
  // If user forces full motion, override prefers-reduced-motion CSS branch
  html.classList.toggle('motion-force', mode === 'full');
  var toggle = document.getElementById('motionToggle');
  if (toggle) {
    toggle.setAttribute('aria-pressed', motionReduced ? 'true' : 'false');
    toggle.textContent = motionReduced
      ? 'OK FINE, FLASH AGAIN'
      : 'DISABLE FLASHING, COWARD';
  }
}

function initMotionToggle() {
  var saved = storageGet(SITE.storageKeys.motion, null);
  var prefers = false;
  try {
    prefers = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  } catch (e) {}
  var mode = saved === 'reduce' || saved === 'full'
    ? saved
    : (prefers ? 'reduce' : 'full');
  applyMotionPreference(mode);

  var toggle = document.getElementById('motionToggle');
  if (!toggle) return;
  function flip() {
    var next = isMotionReduced() ? 'full' : 'reduce';
    storageSet(SITE.storageKeys.motion, next);
    applyMotionPreference(next);
  }
  toggle.addEventListener('click', function(e) {
    e.stopPropagation();
    flip();
  });
  toggle.addEventListener('keydown', function(e) {
    if (e.key === 'Enter' || e.key === ' ') {
      e.preventDefault();
      flip();
    }
  });
}

